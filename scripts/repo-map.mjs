// Writes docs/repo-map.md: every source file with its exported symbols, one line each.
// A short map the agent can read instead of opening every file.
import { readFileSync, writeFileSync, globSync, existsSync } from "node:fs";

const files = globSync("src/**/*.ts").sort();
const lines = ["# Repo map (generated by scripts/repo-map.mjs — do not edit by hand)", ""];
for (const f of files) {
  const src = readFileSync(f, "utf8");
  const names = [
    ...src.matchAll(/^export\s+(?:async\s+)?(?:function|const|type|interface|class)\s+(\w+)/gm),
  ].map((m) => m[1]);
  lines.push(`- ${f}: ${names.length ? names.join(", ") : "(no exports)"}`);
}
const destMapPath = existsSync("docs/lifecycle") ? "docs/lifecycle/repo-map.md" : "docs/repo-map.md";
writeFileSync(destMapPath, lines.join("\n") + "\n");
console.log(`${destMapPath}: ${files.length} files, ~${Math.round(lines.join("\n").length / 4)} tokens`);
